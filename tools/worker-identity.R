# Build-time source identity, not a binary signature or security certificate.
# Run from the package root before compiling or preparing lazy-load data.
local({
  write.changed <- function(text, path) {
    bytes <- charToRaw(paste0(paste(text, collapse = "\n"), "\n"))
    if (file.exists(path) && identical(readBin(path, "raw", file.info(path)$size), bytes))
      return(invisible(NULL))
    con <- file(path, "wb")
    on.exit(close(con))
    writeBin(bytes, con)
  }
  digest <- function(paths) {
    paths <- sort(unique(paths), method = "radix")
    if (!length(paths) || any(!file.exists(paths))) stop("incomplete worker identity inputs")
    sums <- tools::md5sum(paths)
    if (anyNA(sums)) stop("cannot hash worker identity inputs")
    manifest <- paste(paths, unname(sums), sep = "\t")
    tmp <- tempfile("np-worker-identity-", tmpdir = ".")
    on.exit(unlink(tmp))
    writeLines(manifest, tmp, useBytes = TRUE)
    unname(tools::md5sum(tmp))
  }
  r.files <- list.files("R", recursive = TRUE, full.names = TRUE)
  r.files <- setdiff(r.files, "R/zzz-np-worker-identity.R")
  startup <- c("inst/Rprofile", "inst/slavedaemon.R", "inst/Rslaves.sh",
               "inst/MacR64slaves.sh")
  r.id <- digest(c(r.files, "NAMESPACE", startup))
  native <- list.files("src", pattern = "\\.(c|h|cc|cpp|f|f90|inc)$",
                       recursive = TRUE, full.names = TRUE, ignore.case = TRUE)
  native <- setdiff(native, "src/np_worker_identity.h")
  native.id <- digest(c(native, "src/Makevars.in", "src/Makevars.win",
                       "configure.ac", "configure", "configure.win", "tools/worker-identity.R"))
  version <- read.dcf("DESCRIPTION", fields = "Version")[[1L]]
  write.changed(c("# Generated by tools/worker-identity.R; do not edit.",
    sprintf(".npRmpi_worker_source <- list(schema = 1L, version = %s, r = %s, native = %s)",
            deparse(version), deparse(r.id), deparse(native.id))),
    "R/zzz-np-worker-identity.R")
  write.changed(c("/* Generated by tools/worker-identity.R; do not edit. */",
                  sprintf('#define NP_WORKER_NATIVE_SOURCE "%s"', native.id)),
                "src/np_worker_identity.h")
  sources <- list.files("src", pattern = "\\.(c|cc|cpp|f|f90)$", ignore.case = TRUE)
  objects <- sub("\\.[^.]+$", ".o", sources)
  write.changed(c("# Every native object must follow the source identity stamp.",
                  paste(paste(objects, collapse = " "), ": np_worker_identity.h")),
                "src/np_worker_identity_deps.mk")
})
