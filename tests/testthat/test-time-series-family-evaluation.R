test_that("quantile and hat evaluation use fresh aligned RHS variables", {
  old <- options(np.messages = FALSE)
  on.exit(options(old), add = TRUE)
  set.seed(42)
  y <- ts(rnorm(28), frequency = 4)
  f <- y ~ lag(y, -1) + lag(y, -2)
  x <- data.frame(a = as.numeric(y)[2:27], b = as.numeric(y)[1:26])
  response <- as.numeric(y)[3:28]
  new <- data.frame(y = as.numeric(y)[1:18])
  new$y <- ts(new$y, frequency = 4, start = c(2001, 1))
  ex <- data.frame(a = as.numeric(new$y)[2:18], b = as.numeric(new$y)[1:17])
  rbw <- npregbw(f, bws = c(.8, .8), bandwidth.compute = FALSE)
  h <- npreghat(rbw, newdata = new)
  native.h <- npreghat(rbw, txdat = x, y = response, exdat = ex)
  expect_identical(dim(h), c(17L, 26L))
  expect_equal(as.numeric(h), as.numeric(native.h), tolerance = 1e-14)
  bw <- npcdistbw(f, bws = rep(.8, 3), bandwidth.compute = FALSE)
  direct <- npqreg(bws = bw, newdata = new, tau = c(.3, .7), gradients = TRUE, se = TRUE)
  native <- npqreg(bws = bw, txdat = x, tydat = response, exdat = ex,
    tau = c(.3, .7), gradients = TRUE, se = TRUE)
  expect_equal(direct$quantile, native$quantile, tolerance = 1e-14)
  expect_equal(direct$quantgrad, native$quantgrad, tolerance = 1e-14)
  expect_equal(direct$quanterr, native$quanterr, tolerance = 1e-14)
  fit <- npqreg(bws = bw, tau = c(.3, .7))
  expect_equal(predict(fit, newdata = new), native$quantile, tolerance = 1e-14)
  expect_error(npqreg(bws = bw, newdata = data.frame(other = 1:18)), "columns.*y")
  expect_error(npreghat(rbw, newdata = data.frame(other = 1:18)), "columns.*y")
  ordinary <- data.frame(y = response, x = x$a, z = x$b)
  dot.bw <- npcdistbw(y ~ ., data = ordinary, bws = rep(.8, 3),
                      bandwidth.compute = FALSE)
  dot.fit <- npqreg(bws = dot.bw)
  expect_equal(predict(dot.fit, newdata = ordinary[1:3, c("x", "z")]),
    npqreg(bws = dot.bw, txdat = ordinary[c("x", "z")], tydat = response,
      exdat = ordinary[1:3, c("x", "z")])$quantile, tolerance = 1e-14)
})

test_that("mode prevalidation and prediction respect the aligned response roles", {
  old <- options(np.messages = FALSE)
  on.exit(options(old), add = TRUE)
  set.seed(42)
  y <- ts(rnorm(28), frequency = 4)
  cy <- factor(rep(c("a", "b"), 13))
  f <- cy ~ y + lag(y, -2)
  bw <- npcdensbw(f, bws = rep(.25, 3), bandwidth.compute = FALSE)
  fit <- npconmode(bws = bw, probabilities = TRUE)
  new <- data.frame(y = as.numeric(y)[1:18])
  new$y <- ts(new$y, frequency = 4, start = c(2001, 1))
  ex <- data.frame(a = as.numeric(new$y)[3:18], b = as.numeric(new$y)[1:16])
  x <- data.frame(a = as.numeric(y)[3:28], b = as.numeric(y)[1:26])
  direct <- npconmode(bws = bw, newdata = new, probabilities = TRUE)
  native <- npconmode(bws = bw, txdat = x, tydat = cy, exdat = ex, probabilities = TRUE)
  expect_identical(direct$conmode, native$conmode)
  expect_equal(direct$probabilities, native$probabilities, tolerance = 1e-14)
  expect_identical(predict(fit, newdata = new), native$conmode)
  expect_error(predict(fit, newdata = data.frame(other = 1:18)), "columns.*y")
  automatic <- npconmode(f, nmulti = 1L)
  expect_identical(automatic$ntrain, 26L)
  ordinary <- data.frame(cy = cy, a = x$a, b = x$b)
  dot.fit <- npconmode(cy ~ ., data = ordinary, bandwidth.compute = FALSE)
  expect_identical(predict(dot.fit, newdata = ordinary[1:3, c("a", "b")]),
    npconmode(bws = dot.fit$bws, txdat = ordinary[c("a", "b")], tydat = cy,
      exdat = ordinary[1:3, c("a", "b")])$conmode)
})
