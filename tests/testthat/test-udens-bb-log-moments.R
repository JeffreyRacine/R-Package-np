test_that("BB analytic moments preserve the weighted complete law", {
  z <- .np_udens_bb_log_moments(c(1,1),2,c(.2,.3,.5))
  expected <- c(-11/6,-5/6,-1/3)
  expect_equal(z[,1],expected,tolerance=1e-15)
  expect_equal(z[,2],rev(expected),tolerance=1e-15)
  expect_equal(attr(z,"mean"),c(sum(c(.2,.3,.5)*expected),sum(c(.2,.3,.5)*rev(expected))),tolerance=1e-15)
  expect_identical(.np_udens_bb_log_moments(c(1,1),0,1)[1,1],-1)
  swapped <- .np_udens_bb_log_moments(c(.7,2.3),13,rep(1/14,14))
  other <- .np_udens_bb_log_moments(c(2.3,.7),13,rep(1/14,14))
  expect_identical(unname(swapped[,1]),unname(rev(other[,2])))
  expect_identical(attr(swapped,"mean"),rev(attr(other,"mean")))
})
test_that("BB moment validation cannot waive a material law defect", {
  expect_error(.np_udens_bb_log_moments(c(0,1),1,c(.5,.5)),"invalid")
  expect_error(.np_udens_bb_log_moments(c(NA_real_,1),1,c(.5,.5)),"invalid")
  expect_error(.np_udens_bb_log_moments(c(1,1),1.5,c(.5,.5)),"invalid")
  expect_error(.np_udens_bb_log_moments(c(1,1),1,c(-.1,1.1)),"weight")
  expect_error(.np_udens_bb_log_moments(c(1,1),1,c(.4,.4)),"mass")
  expect_error(.np_udens_bb_log_moments(c(1,1),1,1),"dimensions")
  expect_error(.np_udens_bb_log_moments(c("1","1"),1,c(.5,.5)),"numeric")
  expect_error(.np_udens_bb_log_moments(matrix(c(1,1)),1,c(.5,.5)),"numeric")
})
