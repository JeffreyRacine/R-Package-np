test_that("unconditional inverse returns the first crossing for stepped and decreasing estimates", {
  x <- seq(0, 1, length.out = 12L)
  tau <- c(1, .4, 0, .2, .4, .75)
  rows <- function(x) rep_len(c(.15, .4, .4, .2, .75, .5), length(x))
  b <- structure(list(xnames = "x"), class = "dbandwidth")
  local_mocked_bindings(npudist = function(tdat, edat, bws)
    list(fitted.values = rows(edat)), .package = "np")
  grid <- sort(c(seq(-1, 2, length.out = 100L), quantile(x, tau)))
  target <- pmin(.75, pmax(.15, tau))
  expected <- vapply(target, function(t) min(grid[rows(grid) >= t]), numeric(1L))
  names(expected) <- paste0(100 * target, "%")
  observed <- npquantile(x, tau, num.eval = 100L, bws = b)
  expect_identical(observed, expected)
})
